const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);
const CONTINUED = /^ {2,}\S/;

/** Trim spaces/tabs at both ends of a line. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return line.slice(a, b);
}

function isFenceOpen(line) {
  if (!line.startsWith('```')) return null;
  let i = 3;
  let lang = '';
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) { lang += line[i]; i++; }
    else break;
  }
  while (i < line.length && (line.charCodeAt(i) === 32 || line.charCodeAt(i) === 9)) i++;
  return i === line.length ? lang : null;
}

function isFenceClose(line) {
  if (!line.startsWith('```')) return false;
  let i = 3;
  while (i < line.length && (line.charCodeAt(i) === 32 || line.charCodeAt(i) === 9)) i++;
  return i === line.length;
}

/** A heading line's level and text, or null. */
function headingOf(line) {
  let h = 0;
  while (h < 6 && line.charCodeAt(h) === 35) h++;
  if (h === 0) return null;
  if (line.charCodeAt(h) === 35) return null; // 7+ hashes
  const c = line.charCodeAt(h);
  if (c !== 32 && c !== 9) return null;
  let b = line.length;
  while (b > h && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  const text = line.slice(h, b).replace(/^[ \t]+/, '');
  return text === '' ? null : { depth: h, text };
}

function isHr(line) {
  const p = line.startsWith('---') ? 3 : line.startsWith('***') ? 3 : -1;
  if (p === -1) return false;
  for (let i = p; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

function endsParagraph(line) {
  return isBlankLine(line) || isFenceOpen(line) !== null || headingOf(line) !== null || isHr(line);
}

/**
 * The first index in [from, end) where `s` holds `what` outside a backslash
 * escape, or -1. An occurrence is escaped iff an odd run of backslashes
 * stands right before it (the pair-skipping scan's exact equivalent).
 */
function findUnescaped(s, what, from, end) {
  let j = s.indexOf(what, from);
  while (j !== -1 && j + what.length <= end) {
    let b = 0;
    for (let k = j - 1; k >= 0 && s.charCodeAt(k) === 92; k--) b++;
    if (b % 2 === 0) return j;
    j = s.indexOf(what, j + 1);
  }
  return -1;
}

/** The first single * in [from, end) (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from, end) {
  let j = s.indexOf('*', from);
  while (j !== -1 && j < end) {
    let b = 0;
    for (let k = j - 1; k >= 0 && s.charCodeAt(k) === 92; k--) b++;
    if (b % 2 === 1) { j = s.indexOf('*', j + 1); continue; }
    if (j + 1 < end && s.charCodeAt(j + 1) === 42) { j = s.indexOf('*', j + 2); continue; }
    return j;
  }
  return -1;
}

/** Flush the plain segment s[a..b) into `out`, HTML-escaped. */
function pushEsc(out, s, a, b) {
  if (b <= a) return;
  const seg = s.slice(a, b);
  out.push(ESC_TEST.test(seg) ? seg.replace(ESC_RE, (c) => ESCAPES[c]) : seg);
}

const SPECIALS = ['\\', '`', '*', '['];

/** The first index in [from, end) holding a markup character, or -1. */
function nextSpecial(s, from, end) {
  let j = -1;
  for (let k = 0; k < 4; k++) {
    const p = s.indexOf(SPECIALS[k], from);
    if (p !== -1 && p < end && (j === -1 || p < j)) j = p;
  }
  return j;
}

/**
 * `s[a..b)` rendered inline into `out`; `link(target)` resolves a link's
 * href. Plain runs are flushed in bulk (indexOf jumps, no per-character
 * loop); nested strong/em/link text recurses on the same string by range,
 * so no substrings are allocated for it.
 */
function inlineInto(s, a, b, link, out) {
  let i = a;
  while (i < b) {
    const j = nextSpecial(s, i, b);
    if (j === -1) {
      pushEsc(out, s, i, b);
      return;
    }
    if (j > i) pushEsc(out, s, i, j);
    const c = s[j];
    if (c === '\\' && j + 1 < b && ESCAPABLE.has(s[j + 1])) {
      out.push(s[j + 1] === '>' ? '&gt;' : s[j + 1]);
      i = j + 2;
      continue;
    }
    if (c === '`') {
      const k = s.indexOf('`', j + 1);
      if (k !== -1 && k < b && k > j + 1) {
        out.push('<code>');
        pushEsc(out, s, j + 1, k);
        out.push('</code>');
        i = k + 1;
      } else {
        out.push('`');
        i = j + 1;
      }
      continue;
    }
    if (c === '*') {
      if (j + 1 < b && s[j + 1] === '*') {
        const k = findUnescaped(s, '**', j + 2, b);
        if (k !== -1 && k > j + 2) {
          out.push('<strong>');
          inlineInto(s, j + 2, k, link, out);
          out.push('</strong>');
          i = k + 2;
        } else {
          out.push('**');
          i = j + 2;
        }
        continue;
      }
      const k = findSingleStar(s, j + 1, b);
      if (k !== -1 && k > j + 1) {
        out.push('<em>');
        inlineInto(s, j + 1, k, link, out);
        out.push('</em>');
        i = k + 1;
      } else {
        out.push('*');
        i = j + 1;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', j + 1, b);
      const m = k !== -1 && k + 1 < b && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = m === -1 || m >= b ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        out.push('<a href="', escText(link(target)), '">');
        inlineInto(s, j + 1, k, link, out);
        out.push('</a>');
        i = m + 1;
        continue;
      }
    }
    // A '[' with no link, or a backslash that escapes nothing: the character
    // itself is literal text (none of `[` `\` needs HTML escaping).
    out.push(s[j]);
    i = j + 1;
  }
}

/** `s` rendered inline; `link(target)` resolves a link's href. */
function inline(s, link) {
  const out = [];
  inlineInto(s, 0, s.length, link, out);
  return out.join('');
}

/**
 * `src` rendered in one pass over its lines: HTML, table of contents and
 * excerpt. `link` resolves link targets; `slugify` is the per-build cached one.
 */
function renderMarkdown(src, link, slugify) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  const lines = src.split('\n');
  const n = lines.length;
  let i = 0;
  while (i < n) {
    const line = lines[i];
    if (isBlankLine(line)) { i++; continue; }
    const lang = isFenceOpen(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < n && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      let s = `<pre><code${lang === '' ? '' : ` class="language-${escText(lang)}"`}>`;
      for (const l of body) { s += escText(l); s += '\n'; }
      blocks.push(`${s}</code></pre>`);
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inline(heading.text, link);
      blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) { blocks.push('<hr>'); i++; continue; }
    if (line.charCodeAt(0) === 62) {
      const body = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        let l = lines[i].slice(1);
        if (l.charCodeAt(0) === 32) l = l.slice(1);
        body.push(l);
        i++;
      }
      const kept = [];
      for (const l of body) {
        const t = trimLine(l);
        if (t !== '') kept.push(t);
      }
      blocks.push(kept.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inline(kept.join('\n'), link)}</p>\n</blockquote>`);
      continue;
    }
    const bullet = line.length >= 2 && (line.charCodeAt(0) === 45 || line.charCodeAt(0) === 42) && line.charCodeAt(1) === 32;
    let ordered = null;
    if (!bullet) {
      let d = 0;
      while (d < 9 && d < line.length && line.charCodeAt(d) >= 48 && line.charCodeAt(d) <= 57) d++;
      if (d > 0 && line.charCodeAt(d) === 46 && line.charCodeAt(d + 1) === 32) ordered = Number(line.slice(0, d));
    }
    if (bullet || ordered !== null) {
      const isOrdered = ordered !== null;
      const start = isOrdered ? ordered : 1;
      const items = [];
      while (i < n) {
        const l = lines[i];
        let m = null;
        if (isOrdered) {
          let d = 0;
          while (d < 9 && d < l.length && l.charCodeAt(d) >= 48 && l.charCodeAt(d) <= 57) d++;
          if (d > 0 && l.charCodeAt(d) === 46 && l.charCodeAt(d + 1) === 32) m = l.slice(d + 2);
        } else if (l.length >= 2 && (l.charCodeAt(0) === 45 || l.charCodeAt(0) === 42) && l.charCodeAt(1) === 32) {
          m = l.slice(2);
        }
        if (m !== null) {
          items.push([trimLine(m)]);
          i++;
        } else if (CONTINUED.test(l)) {
          items[items.length - 1].push(trimLine(l));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && start !== 1 ? `<ol start="${start}">` : `<${tag}>`;
      let s = `${open}\n`;
      for (const item of items) s += `<li>${inline(item.join('\n'), link)}</li>\n`;
      blocks.push(`${s}</${tag}>`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const html = inline(body.join('\n'), link);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>`);
  }
  return { html: blocks.length === 0 ? '' : `${blocks.join('\n')}\n`, toc, excerpt: excerpt ?? '' };
}

